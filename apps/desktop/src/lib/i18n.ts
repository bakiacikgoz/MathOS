const dictionaries: Record<Lang, Record<MessageKey, string>> = { tr, en }

export function detectLang(): Lang {
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("tr") ? "tr" : "en"
}

export function translate(lang: Lang, key: MessageKey): string {
  return dictionaries[lang][key]
}

export const LangContext = createContext<Lang>("tr")
export function useT() {
  const lang = useContext(LangContext)
  return { lang, t: (key: MessageKey) => translate(lang, key) }
}
